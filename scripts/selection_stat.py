"""One selection statistic for the frozen rules, from the stored v0.11 result files (review C1/C2).

Plain idea: three different deflated Sharpe ratios were published for the same chosen rules
(0.998 at 26 trials, 1.0 at "trials 0", 0.949 at 42), all on the *absolute* portfolio Sharpe,
which every long-biased trial and the no-desk vol-target control pass alike (review C1). This
script prints one number on one statistic and one sample, and shows the old statistic beside it
for the record.

The statistic: ``stats.deflated_sharpe_differential`` on the daily series
``AgenticTrader - B&H vol-target`` (the desk minus the control that took no decisions), design
period 2016-01-04..2021-12-31, 260 periods a year (``render_v08_tables.PORTFOLIO_PPY``). The
trial count is ``len(evaluation.TRIALS)`` (the registry today), with the pre-registry estimate
added as the conservative figure. The trials' own daily portfolio series were never stored, so
their differential Sharpes cannot be measured: the benchmark dispersion is the sampling variance
of a zero-skill differential Sharpe (``stats.null_trial_sharpe_variance``), which treats trials
as independent. The effective-trials figure needs those series too and is reported as not
computable.

Inputs (git-ignored, local only): ``<results>/portfolio_design.csv`` and ``<results>/trials.json``
from ``scripts/measure_v08.py --out results/v11``. No network, no model calls.

Usage: ``python scripts/selection_stat.py [--results results/v11] [--out docs/results/round2/selection_stat.md]``
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from agentic_trader import evaluation  # noqa: E402
from agentic_trader.stats import deflated_sharpe_differential, selection_report  # noqa: E402

PPY = 260.0
DESK, CONTROL = "AgenticTrader", "B&H vol-target"


def _excess(frame: pd.DataFrame, col: str) -> np.ndarray:
    """Return over (t-1, t] minus rf[t-1] / PPY, the pairing ``render_v08_tables`` uses."""
    r = frame[col].to_numpy(float)[1:]
    rf = frame["rf"].to_numpy(float)[:-1] if "rf" in frame else np.zeros_like(r)
    return r - np.where(np.isfinite(rf), rf, 0.0) / PPY


def compute(results: Path) -> dict:
    frame = pd.read_csv(results / "portfolio_design.csv", index_col=0, parse_dates=True)
    trials = json.loads((results / "trials.json").read_text(encoding="utf-8"))["trials"]
    measured = [t["portfolio_sharpe"] for t in trials if t.get("portfolio_sharpe") is not None]
    desk, ctl = _excess(frame, DESK), _excess(frame, CONTROL)
    n_reg = len(evaluation.TRIALS)
    pre = evaluation.PRE_REGISTRY_TRIALS_ESTIMATE
    diff = {k: deflated_sharpe_differential(desk, ctl, n, PPY) for k, n in
            (("registry", n_reg), ("registry_plus_pre_registry", n_reg + pre))}
    diff["registry_raw_difference"] = deflated_sharpe_differential(desk, ctl, n_reg, PPY, match_vol=False)
    old = {
        "desk_at_stored_trials": selection_report(desk, measured, PPY),   # 42 measured: the published v0.11 row
        "desk_at_registry": selection_report(desk, measured, PPY, n_trials=n_reg),
        "control_at_registry": selection_report(ctl, measured, PPY, n_trials=n_reg),
    }
    return {"sample": f"{frame.index[1].date()}..{frame.index[-1].date()}", "ppy": PPY,
            "n_registry": n_reg, "n_pre_registry": pre, "n_stored_trials": len(trials),
            "n_measured_trial_sharpes": len(measured), "differential": diff, "absolute": old}


def _f(x, nd: int = 3) -> str:
    return "n/a" if x is None or (isinstance(x, float) and not math.isfinite(x)) else f"{x:.{nd}f}"


def render(out: dict) -> str:
    d, d2 = out["differential"]["registry"], out["differential"]["registry_plus_pre_registry"]
    raw = out["differential"]["registry_raw_difference"]
    a = out["absolute"]
    lines = [
        "# Selection statistic for the frozen rules (round 2, review C1/C2)",
        "",
        "Generated by `scripts/selection_stat.py` from the stored v0.11 design-period files "
        f"(`results/v11/portfolio_design.csv`, `trials.json`); sample {out['sample']}, "
        f"{d['n']} daily periods, {out['ppy']:g} periods a year.",
        "",
        f"**Selection statistic: deflated Sharpe of desk minus vol-target control = "
        f"{_f(d['deflated_sharpe_prob'])}** at {out['n_registry']} registered trials "
        "(`len(evaluation.TRIALS)`).",
        "",
        "The differential series is `desk - k * control` with `k = sd(desk) / sd(control) = "
        f"{_f(d['control_scale'])}`: the control levered to the desk's volatility, so a positive mean "
        "means a higher Sharpe than the control, and the desk's lower exposure is not counted against it.",
        "",
        "| figure | value |",
        "|---|---:|",
        f"| differential Sharpe (desk - vol-matched control), annualised | {_f(d['sharpe_annual'])} |",
        f"| PSR of the differential Sharpe against 0 | {_f(d['psr_vs_zero'])} |",
        f"| expected max of {out['n_registry']} zero-skill trials, annualised | "
        f"{_f(d['expected_max_sharpe_annual'])} |",
        f"| **differential DSR, {out['n_registry']} trials (registry)** | **{_f(d['deflated_sharpe_prob'])}** |",
        f"| differential DSR, {out['n_registry'] + out['n_pre_registry']} trials "
        f"(registry + pre-registry estimate {out['n_pre_registry']}) | {_f(d2['deflated_sharpe_prob'])} |",
        "| differential DSR, effective trials | not computable: the trials' daily series were not stored |",
        f"| raw difference (k = 1), Sharpe / DSR at {out['n_registry']} trials | "
        f"{_f(raw['sharpe_annual'])} / {_f(raw['deflated_sharpe_prob'])} |",
        "",
        f"Benchmark dispersion: {d['benchmark_variance_source']}. Correlated trials would lower the "
        "benchmark, so with independent trials assumed the figure is conservative in N.",
        "",
        "## The old statistic, for the record (absolute portfolio Sharpe; not a selection test)",
        "",
        "| series | trials | expected max (annual) | absolute DSR |",
        "|---|---:|---:|---:|",
    ]
    for label, key in (("desk (frozen rules), as published in v0.11", "desk_at_stored_trials"),
                       ("desk (frozen rules)", "desk_at_registry"),
                       ("vol-target control, no desk", "control_at_registry")):
        r = a[key]
        lines.append(f"| {label} | {r['trials']} | {_f(r['expected_max_sharpe_annual'])} | "
                     f"{_f(r['deflated_sharpe_prob'])} |")
    lines += ["", "The control row is the C1 failure case: a book that took no decisions scores about the same "
              "absolute DSR as the desk, so that number carries no information about selection. The absolute "
              "rows use the "
              f"{out['n_measured_trial_sharpes']} measured trial portfolio Sharpes for the dispersion.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", default=str(ROOT / "results" / "v11"))
    ap.add_argument("--out", default=None, help="write the markdown block here as well as to stdout")
    args = ap.parse_args(argv)
    res = Path(args.results)
    if not (res / "portfolio_design.csv").exists() or not (res / "trials.json").exists():
        print(f"stored inputs not found under {res}: run scripts/measure_v08.py --out results/v11 first",
              file=sys.stderr)
        return 2
    text = render(compute(res))
    print(text)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
