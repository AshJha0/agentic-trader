#!/usr/bin/env sh
# Hashed dependency locks, one per supported Python: requirements/lock-py3.XX.txt.
#
# Each file pins every package (dev and data extras included) to one version with the
# SHA-256 of every wheel/sdist PyPI lists for it, so `pip install --require-hashes -r` refuses
# anything else (supply-chain pinning) and a published number can be reproduced on that
# Python. Resolved for Linux x86_64 (the CI runners); a Windows install of the same file
# works when the listed wheels cover it, which uv's universal hashes usually do.
#
# Needs uv (https://docs.astral.sh/uv/) and network access to PyPI, so it runs in CI (the
# "Lockfiles" workflow, manual dispatch), not on the maintainer's laptop. Commit the files the
# workflow uploads; ci.yml and paper.yml switch to --require-hashes per Python as soon as the
# matching file exists.
#
#     sh scripts/gen_lockfiles.sh [3.10 3.11 3.12 3.13 3.14]
set -eu
versions="${*:-3.10 3.11 3.12 3.13 3.14}"
mkdir -p requirements
for v in $versions; do
  uv pip compile pyproject.toml --extra dev --extra data \
    --python-version "$v" --python-platform x86_64-unknown-linux-gnu \
    --generate-hashes --no-header --annotation-style line \
    --output-file "requirements/lock-py$v.txt"
  sed -i "1i # Hashed lock for Python $v (Linux x86_64), generated by scripts/gen_lockfiles.sh; do not edit by hand." \
    "requirements/lock-py$v.txt"
done
