"""False-pass rate and power of the amended decisive-cell statistic, by simulation.

Evidence for the claim in the v0.16 pre-registration (amendment of 2026-11-12) that a model
which is a function of the rule, or noise, does not pass, and that real added signal does.
No study row and no model is used: the returns, the rule signal and the model signal are
simulated, at the decisive cell's shape (313 dates, 10 equities and 5 FX pairs).

    python scripts/round0_metric_size.py --seeds 40 > docs/results/v17/round0_metric_size.md

A "pass" is the pre-registered decision rule: the 95 % interval of the statistic above zero.
Under the null the nominal rate is 2.5 %. The legacy column is the first version of the
statistic, Spearman(model - rule, return) over all names pooled.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Callable

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from agentic_trader import study_design as sd  # noqa: E402

Model = Callable[[np.ndarray, np.ndarray, np.random.Generator], np.ndarray]

NO_INFORMATION: dict[str, Model] = {
    "0.5 x rule": lambda q, f, r: 0.5 * q,
    "minus rule": lambda q, f, r: -q,
    "rule rounded to 0.1": lambda q, f, r: np.round(q, 1),
    "rule rounded to 0.5": lambda q, f, r: np.round(2 * q) / 2,
    "clip(2 x rule)": lambda q, f, r: np.clip(2 * q, -1, 1),
    "sign(rule)": lambda q, f, r: np.sign(q),
    "rule cubed": lambda q, f, r: q**3,
    "pure noise": lambda q, f, r: r.normal(size=len(q)),
    "rule + noise, rounded to 0.1": lambda q, f, r: np.round(q + 0.5 * r.normal(size=len(q)), 1),
}
INFORMATION: dict[str, Model] = {
    "rule + 0.10 x return + noise, rounded": lambda q, f, r: np.round(np.tanh(q + 0.10 * f + 0.5 * r.normal(size=len(q))), 1),
    "rule + 0.20 x return + noise, rounded": lambda q, f, r: np.round(np.tanh(q + 0.20 * f + 0.5 * r.normal(size=len(q))), 1),
}


def rows(model: Model, strength: float, dates: int, seed: int, heavy: bool) -> list[dict]:
    rng = np.random.default_rng(seed)
    out: list[dict] = []
    for d in range(dates):
        for cls, n in (("equity", 10), ("fx", 5)):
            f = rng.standard_t(3, size=n) if heavy else rng.normal(size=n)
            q = np.tanh(strength * f + rng.normal(size=n))  # a bounded rule signal, as the desk's is
            m = model(q, f, rng)
            out += [
                {
                    "as_of": f"d{d:03d}",
                    "asset_class": cls,
                    "signal_rule": float(q[i]),
                    "signal_model": float(m[i]),
                    "fwd_ret": float(f[i]),
                }
                for i in range(n)
            ]
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--seeds", type=int, default=40)
    ap.add_argument("--dates", type=int, default=313)
    a = ap.parse_args(argv)
    print("# Size and power of the amended decisive-cell statistic (simulation)\n")
    print(
        f"Generated by `python scripts/round0_metric_size.py --seeds {a.seeds} --dates {a.dates}`. "
        f"{a.dates} dates, 10 + 5 names, {a.seeds} seeds per row. Rule signal = tanh(strength x return + noise). "
        "Pass = 95 % interval above zero (nominal 2.5 % under the null). Evidence class: simulation; "
        "no study row is used.\n"
    )
    for heavy in (False, True):
        for strength in (0.30, -0.05):
            print(f"\n## Rule strength {strength:+.2f}, returns {'Student t, 3 d.f.' if heavy else 'normal'}\n")
            print("| model | adds information | rule IC | residual IC (mean) | pass share | legacy (mean) | legacy pass share |")
            print("|---|---|---:|---:|---:|---:|---:|")
            for label, group in (("no", NO_INFORMATION), ("yes", INFORMATION)):
                for name, model in group.items():
                    ic, ps, lg, lp, ru = [], [], [], [], []
                    for seed in range(a.seeds):
                        res = sd.incremental_ic(rows(model, strength, a.dates, seed, heavy))
                        p, leg = res["primary"], res["legacy_model_minus_rule"]
                        ic.append(p["ic"])
                        ps.append(p["ci95"][0] > 0)
                        lg.append(leg["ic"])
                        lp.append(leg["ci95"][0] > 0)
                        ru.append(res["rule"]["ic"])
                    print(
                        f"| {name} | {label} | {np.mean(ru):+.3f} | {np.mean(ic):+.4f} | {np.mean(ps):.2f} | "
                        f"{np.mean(lg):+.4f} | {np.mean(lp):.2f} |",
                        flush=True,
                    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
